"""Build the browser version of the playtest from the same rules as rules/play.py.

    python web/build.py

Reads rules/*.csv and events/*.yaml into web/data.js, crops the Adriatic coastline, draws the d20 faces with
design/source/dice.py, and makes small web images of the advisor cards and wind
pieces in web/img/. Run it again after changing a CSV or a card: the web game then
plays by the new numbers. The rules engine is web/engine.js (rules v2); the
terminal game rules/play.py is frozen at v1.
"""
import csv
import glob
import json
import math
import os
import sys

import yaml
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
RULES = os.path.join(ROOT, "rules")
PIECES = os.path.join(ROOT, "design", "pieces")
IMG = os.path.join(HERE, "img")
sys.path.insert(0, os.path.join(ROOT, "design", "source"))
from dice import die_svg, STONES  # noqa: E402
from advisors import emblem  # noqa: E402
from make import GOLD  # noqa: E402


def read_csv(name):
    with open(os.path.join(RULES, name), encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def cards():
    out = []
    for path in sorted(glob.glob(os.path.join(ROOT, "events", "*.yaml"))):
        if os.path.basename(path).startswith("_"):
            continue
        with open(path, encoding="utf-8") as f:
            out.append(yaml.safe_load(f))
    return out


# The Adriatic for the map tab: Natural Earth land, cropped and projected (see design/source/ne/)
MAP = {"lon0": 12.2, "lon1": 20.4, "lat0": 40.2, "lat1": 46.2, "w": 900}
MAP["kx"] = MAP["w"] / (MAP["lon1"] - MAP["lon0"])
MAP["ky"] = MAP["kx"] / math.cos(math.radians(43.2))
MAP["h"] = round((MAP["lat1"] - MAP["lat0"]) * MAP["ky"])


def project(lon, lat):
    return (lon - MAP["lon0"]) * MAP["kx"], (MAP["lat1"] - lat) * MAP["ky"]


def coastline():
    """Land as SVG path data in the map's 900-wide box."""
    paths = []
    for name in ("ne_10m_land", "ne_10m_minor_islands"):
        with open(os.path.join(ROOT, "design", "source", "ne", name + ".geojson"), encoding="utf-8") as f:
            feats = json.load(f)["features"]
        for feat in feats:
            g = feat["geometry"]
            for poly in (g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]):
                ring = poly[0]
                xs, ys = [p[0] for p in ring], [p[1] for p in ring]
                if max(xs) < MAP["lon0"] - 1 or min(xs) > MAP["lon1"] + 1 or max(ys) < MAP["lat0"] - 1 or min(ys) > MAP["lat1"] + 1:
                    continue
                pts = []
                for lon, lat in ring:
                    x, y = project(lon, lat)
                    x, y = min(max(x, -30), MAP["w"] + 30), min(max(y, -30), MAP["h"] + 30)
                    if not pts or abs(pts[-1][0] - x) + abs(pts[-1][1] - y) > 1.2:
                        pts.append((x, y))
                if len(pts) > 3:
                    paths.append("M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z")
    return " ".join(paths)


def dice():
    # the page loads Caesar Dressing from Google Fonts under its full name
    return {st: [die_svg(n, st, f"{st[0]}{n}").replace('font-family="Caesar"', "font-family=\"'Caesar Dressing'\"")
                 for n in range(1, 21)] for st in STONES}


def emblems():
    """Each advisor's sign (galley, vine rod, scales, coins, lituus) as a small SVG for the badge on his coin."""
    out = {}
    for a in read_csv("advisors.csv"):
        aid = a["id"]
        grad = GOLD.replace('id="gold"', f'id="gold-{aid}"')
        out[aid] = (f'<svg viewBox="-6 -6 132 132" aria-hidden="true"><defs>{grad}</defs>'
                    + emblem(aid).replace("url(#gold)", f"url(#gold-{aid})") + "</svg>")
    return out


def images():
    os.makedirs(IMG, exist_ok=True)
    for path in glob.glob(os.path.join(PIECES, "advisors", "*.png")):
        im = Image.open(path).convert("RGBA").resize((600, 840), Image.LANCZOS)
        im.save(os.path.join(IMG, "advisor-" + os.path.basename(path)[:-4] + ".webp"), quality=86)
    for path in glob.glob(os.path.join(PIECES, "winds", "*.png")):
        im = Image.open(path).convert("RGBA")
        im.thumbnail((420, 420), Image.LANCZOS)
        im.save(os.path.join(IMG, os.path.basename(path)[:-4] + ".webp"), quality=84)


if __name__ == "__main__":
    data = {
        "numbers": read_csv("numbers.csv"), "decrees": read_csv("decrees.csv"),
        "seasons": read_csv("seasons.csv"), "advisors": read_csv("advisors.csv"),
        "winds": read_csv("winds.csv"), "buildings": read_csv("buildings.csv"),
        "goods": read_csv("goods.csv"), "towns": read_csv("towns.csv"), "tribes": read_csv("tribes.csv"),
        "cards": cards(), "dice": dice(), "emblems": emblems(), "map": dict(MAP, land=coastline()),
    }
    with open(os.path.join(HERE, "data.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by web/build.py from rules/ and events/. Do not edit by hand.\n")
        f.write("window.GAME_DATA = " + json.dumps(data, ensure_ascii=False, default=str) + ";\n")
    images()
    print("ok", len(data["cards"]), "cards,", os.path.getsize(os.path.join(HERE, "data.js")) // 1024, "KB data")
